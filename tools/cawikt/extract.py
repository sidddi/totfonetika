#!/usr/bin/env python3
"""Extract Catalan pronunciations from a ca.wiktionary (Viccionari) dump.

Usage: python -I extract.py cawiktionary-latest-pages-articles.xml.bz2 OUTDIR [WORKERS]
Needs: pip install "git+https://github.com/tatuylonen/wikitextprocessor"

Writes:
  OUTDIR/cawikt.json       { word: { central, valencia, nordoccidental, balear, rossellones } }, each a list of IPA strings
  OUTDIR/cawikt-meta.json  { word: kind }  kind = auto (template with no pronunciation parameters: generated from the
                           spelling), hints (vowel/-r/x... marks or respelling, still generated by the module) or
                           manual (at least one /IPA/ written by hand for one of the five varieties)

{{ca-pron}} (Plantilla:ca-pron -> Mòdul:ca-pron, generator in Mòdul:ca-pron/AFI) is expanded with wikitextprocessor
using the templates and modules of the same dump, so the IPA is what the wiki shows. It covers central, balear,
nord-occidental and valencià; septentrional (rossellonès) only appears when the entry gives sept=.
"""
import bz2, json, os, re, shutil, sys
import xml.etree.ElementTree as ET
from multiprocessing import Pool

CA = re.compile(r'^==\s*\{\{-ca-\}\}\s*==\s*$', re.M)
L2 = re.compile(r'^==[^=].*==\s*$', re.M)
SPAN = re.compile(r'<span class="IPA"[^>]*>([^<]*)</span>')
# parameters that change the pronunciation of one of our five varieties
PRON_KEYS = {'1', 'tipus', 'centr', 'centr2', 'bal', 'bal2', 'nocc', 'nocc2', 'val', 'val2', 'or', 'or2', 'occ', 'occ2', 'sept'}
LABEL = {'central': ['central'], 'balear': ['balear'], 'nord-occidental': ['nordoccidental'], 'valencià': ['valencia'],
         'septentrional': ['rossellones'], 'oriental': ['central', 'balear'], 'occidental': ['nordoccidental', 'valencia']}
ALL4 = ['central', 'balear', 'nordoccidental', 'valencia']


def pages(path):
    title = ns = text = None
    for _, el in ET.iterparse(bz2.open(path), events=('end',)):
        tag = el.tag.rsplit('}', 1)[-1]
        if tag == 'title': title = el.text
        elif tag == 'ns': ns = el.text
        elif tag == 'text': text = el.text or ''
        elif tag == 'page':
            yield title, ns, text
            el.clear()


def ca_pron_calls(sec):
    out, i = [], 0
    while (j := sec.find('{{ca-pron', i)) >= 0:
        if sec[j + 9:j + 10] not in ('|', '}', '\n', ' '): i = j + 9; continue
        d, k = 0, j
        while k < len(sec):
            if sec.startswith('{{', k): d += 1; k += 2
            elif sec.startswith('}}', k):
                d -= 1; k += 2
                if d == 0: break
            else: k += 1
        out.append(sec[j:k]); i = k
    return out


def params(call):
    body = re.sub(r'<!--.*?-->', '', call[2:-2], flags=re.S).split('|')[1:]
    vals, n = {}, 0
    for p in body:
        p = p.strip()
        m = re.match(r'^([\w-]+)\s*=(.*)$', p, re.S)
        if m: vals[m.group(1)] = m.group(2).strip()
        else: n += 1; vals[str(n)] = p
    return {k: v for k, v in vals.items() if v}


def kind(calls):
    k = 'auto'
    for c in calls:
        v = {a: b for a, b in params(c).items() if a in PRON_KEYS}
        if any('/' in b for b in v.values()): return 'manual'
        if v: k = 'hints'
    return k


def parse(html):
    """Expanded {{ca-pron}} -> {variety: [ipa]}. Labels: Oriental/Occidental rows, then central, balear, ... inline."""
    out = {}
    body = html.split('</sup>:', 1)[-1]
    # entries with audio wrap the IPA in {{#tag:phonos|<span ...>/x/</span>|file="..."}}
    body = re.sub(r'\{\{#tag:phonos\|', '', body)
    body = re.sub(r'\|file="[^"]*"\}\}', '', body)
    if '{|' not in body:  # single line: "oriental /x/, occidental /y/" or just "/x/" for all
        rows = [('', body)]
    else:
        rows = []
        for r in body.split('\n|-\n'):
            cells = r.split('||', 1)
            if len(cells) == 2: rows.append((re.sub(r'[|:]|&nbsp;', '', cells[0].split('\n')[-1]).strip().lower(), cells[1]))
    group = ''
    for g, content in rows:
        if g: group = g
        if group == 'informal': continue
        target = LABEL.get(group, ALL4)
        for m in re.finditer(r'([^«»]*?)<span class="IPA"[^>]*>([^<]*)</span>', content):
            label = re.sub(r'<[^>]+>|\[\[[^]]*\]\]', '', m.group(1)).strip(' ,').lower()
            if label:
                target = LABEL.get(label)  # None for gironí, alguerès: skip those
            if target is None: continue
            ipa = m.group(2).strip()
            for t in target:
                if ipa not in out.setdefault(t, []): out[t].append(ipa)
    return out


W = None
def init(db):
    global W
    from wikitextprocessor import Wtp
    path = f'{db}.{os.getpid()}'; shutil.copy(db, path)
    W = Wtp(db_path=path, lang_code='ca', project='wiktionary')


def work(item):
    title, calls = item
    W.start_page(title)
    res = {}
    for c in calls:
        try:
            for k, v in parse(W.expand(c)).items():
                res.setdefault(k, []).extend(x for x in v if x not in res.get(k, []))
        except Exception:
            pass
    return title, res, kind(calls)


def main(dump, outdir, workers=4):
    from wikitextprocessor import Wtp
    os.makedirs(outdir, exist_ok=True)
    db = os.path.join(outdir, 'wtp.db')
    if os.path.exists(db): os.remove(db)
    wtp = Wtp(db_path=db, lang_code='ca', project='wiktionary')
    entries = []
    for title, ns, text in pages(dump):
        if ns in ('10', '828'):
            wtp.add_page(title, int(ns), text, model='Scribunto' if ns == '828' and not title.endswith('.css') else 'wikitext')
        elif ns == '0' and (m := CA.search(text)):
            n = L2.search(text, m.end())
            calls = ca_pron_calls(text[m.end(): n.start() if n else len(text)])
            if calls: entries.append((title, calls))
    wtp.db_conn.commit(); wtp.close_db_conn()
    print(f'pages with {{{{ca-pron}}}}: {len(entries)}', flush=True)
    result, meta = {}, {}
    with Pool(workers, initializer=init, initargs=(db,)) as pool:
        for i, (t, res, k) in enumerate(pool.imap_unordered(work, entries, chunksize=200)):
            if res: result[t] = res; meta[t] = k
            if i % 20000 == 0: print(i, flush=True)
    for f in os.listdir(outdir):
        if f.startswith('wtp.db'): os.remove(os.path.join(outdir, f))
    order = ['central', 'valencia', 'nordoccidental', 'balear', 'rossellones']
    result = {w: {k: result[w][k] for k in order if k in result[w]} for w in sorted(result)}
    json.dump(result, open(os.path.join(outdir, 'cawikt.json'), 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    json.dump(dict(sorted(meta.items())), open(os.path.join(outdir, 'cawikt-meta.json'), 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    print(f'with pronunciation: {len(result)}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 4)
